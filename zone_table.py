def find_plan(name):
    """案件的計畫區名稱(可能含「變更…案」) → 表上的名稱；內埔豐田要先比長的，不能配到內埔"""
    n = re.sub(r"\s", "", name or "").replace("臺", "台")
    hit = [k for k in TABLE if k in n]
    return max(hit, key=len) if hit else None


def lookup(plan, zone):
    """回傳 dict(plan, zone, bcr, far, note)；查不到回 None。住一/住二 依分區名稱挑，分不出來就全部回傳"""
    key = find_plan(plan)
    if not key or not zone:
        return None
    zs = TABLE[key]["zones"]
    z = next((k for k in zs if k[:2] in zone), None)
    if not z:
        return None
    bcr, far = list(zs[z][0]), list(zs[z][1])
    m = re.search(r"第?([一二])種?住|住([一二])", zone)
    if m:
        tag = "住" + (m.group(1) or m.group(2)) + "："
        one = [x[len(tag):] for x in far if x.startswith(tag)]
        far = one or far
    return dict(plan=key, zone=z, bcr=bcr, far=far, note=TABLE[key]["note"])


def rows(text=""):
    """查閱視窗用：[(計畫, 分區, 建蔽率, 容積率, 備註)]；text 過濾計畫或分區"""
    out = []
    for p, v in TABLE.items():
        for z, (b, f) in v["zones"].items():
            if not text or text in p or text in z:
                out.append((p, z, "、".join(b), "、".join(f), v["note"]))
    return out


def open_viewer(parent, hint="", on_pick=None):
    """查閱視窗：打字過濾；雙擊一列 → on_pick(建蔽率, 容積率)"""
    import tkinter as tk
    from tkinter import ttk
    fam = "Microsoft JhengHei"
    win = tk.Toplevel(parent)
    win.title("屏東縣建蔽率、容積率對照表")
    win.configure(bg="#FBF1DE")
    win.geometry("900x640")
    top = tk.Frame(win, bg="#FBF1DE")
    top.pack(fill=tk.X, padx=14, pady=(12, 6))
    tk.Label(top, text="找計畫區或分區：", font=(fam, 14), bg="#FBF1DE", fg="#1C1C1E").pack(side=tk.LEFT)
    var = tk.StringVar(master=win, value=hint)
    ent = tk.Entry(top, textvariable=var, font=(fam, 14))
    ent.pack(side=tk.LEFT, fill=tk.X, expand=True, padx=(6, 0))
    st = ttk.Style(win)
    st.configure("Zone.Treeview", font=(fam, 13), rowheight=32)
    st.configure("Zone.Treeview.Heading", font=(fam, 13, "bold"))
    cols = (("plan", "都市計畫", 260), ("zone", "分區", 200), ("bcr", "建蔽率%", 120), ("far", "容積率%", 170), ("note", "備註", 120))
    box = tk.Frame(win)
    box.pack(fill=tk.BOTH, expand=True, padx=14)
    tv = ttk.Treeview(box, columns=[c[0] for c in cols], show="headings", style="Zone.Treeview")
    for k, t, w in cols:
        tv.heading(k, text=t)
        tv.column(k, width=w, anchor="w")
    sb = ttk.Scrollbar(box, command=tv.yview)
    tv.configure(yscrollcommand=sb.set)
    sb.pack(side=tk.RIGHT, fill=tk.Y)
    tv.pack(side=tk.LEFT, fill=tk.BOTH, expand=True)

    def fill(*_):
        tv.delete(*tv.get_children())
        for r in rows(var.get().strip()):
            tv.insert("", tk.END, values=r)
    var.trace_add("write", fill)
    fill()

    def pick(e=None):
        sel = tv.selection()
        if sel and on_pick:
            v = tv.item(sel[0], "values")
            on_pick(v[2], v[3])
            win.destroy()
    tv.bind("<Double-1>", pick)
    tip = "雙擊一列帶入建蔽率、容積率。" if on_pick else ""
    tk.Label(win, text=f"{tip}資料來源：{SOURCE}。僅供參考，應依公布之計畫書為準。", font=(fam, 13), bg="#FBF1DE",
             fg="#3A3A3C", anchor="w", wraplength=860, justify="left").pack(fill=tk.X, padx=14, pady=(6, 12))
    return win
